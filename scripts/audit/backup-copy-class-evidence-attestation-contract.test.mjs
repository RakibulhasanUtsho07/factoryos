import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import test from 'node:test';

const readRepoFile = (path) => readFile(resolve(process.cwd(), path), 'utf8');

test('backup copy-class evidence requires a trusted owner signature bound to the complete claim', async () => {
  const helper = await readRepoFile('services/api/src/saas/backup-copy-class-evidence-attestation.ts');
  const artifactReader = await readRepoFile('services/api/src/saas/backup-copy-class-evidence-artifact-reader.ts');
  const artifactReaderSpec = await readRepoFile('services/api/src/saas/backup-copy-class-evidence-artifact-reader.spec.ts');
  const helperSpec = await readRepoFile('services/api/src/saas/backup-copy-class-evidence-attestation.spec.ts');
  const dto = await readRepoFile('services/api/src/saas/dto/create-saas-backup-copy-class-coverage.dto.ts');
  const service = await readRepoFile('services/api/src/saas/saas-tenant-backup-copy-class-coverage.service.ts');
  const propagation = await readRepoFile('services/api/src/saas/saas-tenant-propagation.service.ts');
  const saga = await readRepoFile('services/api/src/saas/saas-tenant-propagation.saga.spec.ts');
  const migration = await readRepoFile('migrations/228_saas_tenant_backup_copy_class_coverage.sql');
  const referenceMigration = await readRepoFile('migrations/229_saas_backup_copy_class_evidence_reference.sql');
  const apiEnv = await readRepoFile('services/api/.env.example');
  const runbook = await readRepoFile('docs/external-erasure-backup-copy-retention-runbook.md');
  const sqlContract = await readRepoFile('services/api/test/saas-tenant-propagation-contract.sql');
  const signingDoc = await readRepoFile('docs/backup-copy-class-evidence-attestation.md');
  const signer = await readRepoFile('scripts/security/sign-backup-copy-class-evidence.mjs');
  const signerSpec = await readRepoFile('scripts/security/sign-backup-copy-class-evidence.test.mjs');

  assert.match(helper, /factoryos\.backup-copy-class-evidence-attestation\/v1/);
  assert.match(helper, /publicKey\.asymmetricKeyType !== 'ed25519'/);
  assert.match(helper, /ServiceUnavailableException/);
  assert.match(helper, /publicKeyPem\.includes\('PRIVATE KEY'\)/);
  assert.match(helper, /trustedKey\.ownerReference !== payload\.attestationOwnerReference/);
  assert.match(helper, /attestationOwnerReference !== payload\.dataOwnerReference/);
  assert.match(helper, /verify\(null, message, publicKey, signature\)/);
  assert.match(helper, /payload\.evidenceSha256/);
  assert.match(helperSpec, /different evidence digest/);
  assert.match(helperSpec, /absent or malformed/);
  assert.match(dto, /attestation_key_id/);
  assert.match(dto, /attestation_owner_reference/);
  assert.match(dto, /attestation_signature/);
  assert.match(service, /verifyBackupCopyClassEvidenceAttestation\(attestation,attestationSignature\)/);
  assert.match(service, /attestationSignatureSha256/);
  assert.match(service, /attestation_signature/);
  assert.match(propagation, /verifyBackupCopyClassEvidenceAttestation\(attestation, decision\.attestation_signature\)/);
  assert.match(propagation, /attestationSignatureSha256/);
  assert.match(propagation, /Backup copy-class evidence attestation is invalid or its signer is no longer trusted/);
  assert.match(saga, /previously trusted evidence signing key is removed/);
  assert.match(saga, /accepted evidence signature has been tampered with/);
  assert.match(migration, /attestation_key_id varchar/);
  assert.match(migration, /attestation_owner_reference varchar/);
  assert.match(migration, /attestation_signature varchar\(86\)/);
  assert.match(migration, /NEW\.attestation_signature[\s\S]*?OLD\.attestation_signature/);
  assert.match(migration, /attestation_owner_reference IN \(data_owner_reference,infrastructure_owner_reference\)/);
  assert.ok(sqlContract.includes('attestation_key_id,attestation_owner_reference,attestation_signature'));
  assert.match(sqlContract, /pending backup evidence signature was mutable/);
  assert.match(apiEnv, /FACTORYOS_BACKUP_COPY_EVIDENCE_TRUSTED_KEYS_JSON=\[\]/);
  assert.match(runbook, /signed backup copy-class evidence/i);
  assert.match(signingDoc, /does not replace independent reviewer approval/);
  assert.match(signer, /Evidence pack digest does not match payload evidence_sha256/);
  assert.match(signer, /privateKey\.asymmetricKeyType !== 'ed25519'/);
  assert.ok(artifactReader.includes('FACTORYOS_BACKUP_COPY_EVIDENCE_ROOT_DIR'));
  assert.ok(artifactReader.includes('O_NOFOLLOW'));
  assert.ok(artifactReader.includes('MAX_ARTIFACT_BYTES = 16 * 1024 * 1024'));
  assert.ok(artifactReader.includes('actualDigest !== expectedDigestValue'));
  assert.ok(artifactReader.includes('before.mtimeNs === after.mtimeNs'));
  assert.ok(artifactReaderSpec.includes('rejects digest mismatch'));
  assert.ok(artifactReaderSpec.includes('rejects symlinks and non-regular files'));
  assert.ok(artifactReaderSpec.includes('rejects oversized artifacts'));
  assert.ok(service.includes('evidenceArtifactReader.verifyArtifact(evidenceReference,evidenceSha256)'));
  assert.ok(service.includes('evidenceArtifactReader.verifyArtifact(current.evidence_reference,current.evidence_sha256)'));
  assert.ok(propagation.includes('backupEvidenceArtifactReader.verifyArtifact(decision.evidence_reference, decision.evidence_sha256)'));
  assert.ok(dto.includes('@Matches(/^[A-Za-z0-9][A-Za-z0-9._-]{0,199}$/) evidence_reference'));
  assert.ok(referenceMigration.includes("evidence_reference ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,199}});
"));
  assert.ok(signer.includes('single opaque artifact identifier, not a URL or path'));
  assert.ok(signerSpec.includes('URL and path references'));
});
